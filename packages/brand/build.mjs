// Generates the platform files from tokens.json (single source of truth):
//   apps/web/src/brand/tokens.css      — CSS variables + section/tier/heat classes (site)
//   apps/admin/public/tokens.css       — same variables for the Hub
//   apps/mobile/src/lib/brand.ts       — typed tokens for React Native
// Run: node packages/brand/build.mjs   (packages/brand/brand.test.ts fails if outputs are stale)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const T = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const G = JSON.parse(readFileSync(join(here, 'glossary.json'), 'utf8'));
const HEAD = '/* GENERATED by packages/brand/build.mjs from packages/brand/tokens.json — do not edit by hand. */\n';

export function css() {
  const v = (o) => Object.entries(o).map(([k, x]) => `  --${k}: ${x};`).join('\n');
  const core = (m) => v({ bg: T.core[m].bg, elev: T.core[m].elev, ink: T.core[m].ink, muted: T.core[m].muted, line: T.core[m].line, chip: T.core[m].chip, saffron: T.core[m].brand, palm: T.core[m].palm, clay: T.core[m].clay, tile: T.core[m].tile });
  const sec = (s, m) => {
    const c = T.sections[s][m];
    return `  --accent: ${c.from};\n  --accent-2: ${c.to};\n  --accent-ink: ${c.ink};\n  --accent-text: ${c.text};\n  --accent-soft: color-mix(in srgb, ${c.from} 14%, transparent);\n  --accent-glow: color-mix(in srgb, ${c.from} 45%, transparent);`;
  };
  let out = HEAD;
  out += `:root {\n${core('light')}\n${sec('deals', 'light')}\n  --font-stack: ${T.font.stack};\n${Object.entries(T.radius).map(([k, x]) => `  --r-${k}: ${x}px;`).join('\n')}\n${Object.entries(T.shadow).map(([k, x]) => `  --sh-${k}: ${x};`).join('\n')}\n${Object.entries(T.motion).map(([k, x]) => `  --m-${k}: ${x};`).join('\n')}\n${Object.entries(T.type).map(([k, [s, l]]) => `  --t-${k}: ${s}px;\n  --lh-${k}: ${l}px;`).join('\n')}\n${Object.entries(T.state).map(([k, x]) => `  --st-${k}: ${x};`).join('\n')}\n}\n`;
  out += `.dark {\n${core('dark')}\n${sec('deals', 'dark')}\n}\n`;
  for (const s of Object.keys(T.sections)) {
    out += `[data-section="${s}"] {\n${sec(s, 'light')}\n}\n.dark [data-section="${s}"], .dark[data-section="${s}"] {\n${sec(s, 'dark')}\n}\n`;
  }
  for (const [id, t] of Object.entries(T.tiers)) out += `.tier-${id} { --tier: ${t.from}; --tier-2: ${t.to}; --tier-ink: ${t.ink}; }\n`;
  const names = ['', 'cool', 'warm', 'hot', 'blaze'];
  T.heat.stops.forEach((c, i) => { out += `.temp-${i}${names[i] ? `, .heat-${names[i]}` : ''} { --heat: ${c}; --heat-ink: ${T.heat.ink[i]}; }\n`; });
  return out;
}

export function rn() {
  const sections = Object.fromEntries(Object.entries(T.sections).map(([k, s]) => [k, { ar: s.ar, emoji: s.emoji, light: s.light, dark: s.dark }]));
  return `${HEAD}export const brand = ${JSON.stringify({ font: T.font, type: T.type, radius: T.radius, motion: T.motion, core: T.core, sections, tiers: T.tiers, heat: T.heat, state: T.state }, null, 2)} as const;
export type SectionId = keyof typeof brand.sections;
export type TierId = keyof typeof brand.tiers;
/** Deal heat 0..4 from a 0..100 deal score. */
export function heatLevel(score: number): 0 | 1 | 2 | 3 | 4 {
  const t = brand.heat.thresholds;
  return (score >= t[4] ? 4 : score >= t[3] ? 3 : score >= t[2] ? 2 : score >= t[1] ? 1 : 0) as 0 | 1 | 2 | 3 | 4;
}
export const glossary = ${JSON.stringify(Object.fromEntries(G.terms.map((t) => [t.id, { ar: t.ar, en: t.en, ...(t.button ? { button: t.button } : {}), ...(t.full ? { full: t.full } : {}) }])), null, 2)} as const;
`;
}

export function webTs() {
  return `${HEAD}// Route → section map and helpers for the site (same data as the app and the Hub).
export const SECTION_ROUTES = ${JSON.stringify(T.routes)} as const;
export type SectionId = keyof typeof SECTION_ROUTES;
export function sectionFor(path: string): SectionId {
  const seg = '/' + (path.split('/')[1] ?? '');
  for (const [id, list] of Object.entries(SECTION_ROUTES)) if ((list as readonly string[]).includes(seg === '/' ? '/' : seg)) return id as SectionId;
  return 'deals';
}
export const HEAT_THRESHOLDS = ${JSON.stringify(T.heat.thresholds)} as const;
export function heatLevel(score: number): 0 | 1 | 2 | 3 | 4 {
  const t = HEAT_THRESHOLDS;
  return (score >= t[4] ? 4 : score >= t[3] ? 3 : score >= t[2] ? 2 : score >= t[1] ? 1 : 0) as 0 | 1 | 2 | 3 | 4;
}
export const GLOSSARY = ${JSON.stringify(Object.fromEntries(G.terms.map((t) => [t.id, { ar: t.ar, en: t.en }])))} as const;
`;
}

export const outputs = () => ({
  'apps/web/src/brand/tokens.css': css(),
  'apps/web/src/brand/tokens.ts': webTs(),
  'apps/admin/public/tokens.css': css(),
  'apps/mobile/src/lib/brand.ts': rn(),
});

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [f, s] of Object.entries(outputs())) {
    mkdirSync(dirname(join(root, f)), { recursive: true });
    writeFileSync(join(root, f), s);
    console.log('wrote', f);
  }
}
